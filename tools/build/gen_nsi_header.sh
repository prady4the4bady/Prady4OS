#!/usr/bin/env bash
# Generate build/musl/include/pradyos_nsi.h from kernel/syscall/syscall.h.
# Group 6 item 32, DDR-869.
#
# WHY GENERATED. user/include/pradyos.h needs the NSI numbers, and a hand-copied
# table would be a SECOND source of truth that drifts silently — the defect this
# project has hit five times (DDR-817/822/825/833/835). Generating means the two
# cannot disagree: renumber a call in the kernel and this header follows on the
# next build, or the build fails.
#
# It FAILS rather than emitting a partial header. An empty or short header still
# compiles for any program that happens not to use the missing call, so the
# breakage would surface later and somewhere else.
set -euo pipefail

cd "$(dirname "$0")/../.."
SRC=kernel/syscall/syscall.h
OUT=${1:-build/musl/include/pradyos_nsi.h}

[ -f "$SRC" ] || { echo "gen_nsi: $SRC missing" >&2; exit 1; }
mkdir -p "$(dirname "$OUT")"

# Only `#define SYS_<NAME> <number>` lines. The trailing comments carry prose
# with parentheses and slashes, so the number is captured positionally rather
# than by trying to strip the comment.
tmp=$(mktemp)
{
  echo "/* GENERATED by tools/build/gen_nsi_header.sh from $SRC — DO NOT EDIT."
  echo " *"
  echo " * Edit the kernel header instead. This file exists so ring-3 and the"
  echo " * kernel cannot hold two different opinions about a syscall number."
  echo " */"
  echo "#ifndef PRADYOS_NSI_H"
  echo "#define PRADYOS_NSI_H"
  echo
  grep -oE '^#define[[:space:]]+SYS_[A-Z0-9_]+[[:space:]]+[0-9]+' "$SRC" \
    | awk '{ printf "#define %-26s %s\n", $2, $3 }'
  echo
  echo "#endif /* PRADYOS_NSI_H */"
} > "$tmp"

n=$(grep -c '^#define SYS_' "$tmp" || true)
kernel_n=$(grep -cE '^#define[[:space:]]+SYS_[A-Z0-9_]+[[:space:]]+[0-9]+' "$SRC" || true)

if [ "$n" -eq 0 ]; then
  rm -f "$tmp"
  echo "gen_nsi: FAILED — parsed 0 syscall numbers from $SRC." >&2
  echo "gen_nsi: refusing to emit an empty header: it would compile fine for" >&2
  echo "gen_nsi: any program not using the missing calls, so the breakage" >&2
  echo "gen_nsi: would surface later and somewhere unrelated." >&2
  exit 1
fi
if [ "$n" -ne "$kernel_n" ]; then
  rm -f "$tmp"
  echo "gen_nsi: FAILED — emitted $n defines but the kernel header has $kernel_n." >&2
  exit 1
fi

# Only rewrite on change, so an unchanged header does not retrigger every
# dependent compile.
if [ -f "$OUT" ] && cmp -s "$tmp" "$OUT"; then
  rm -f "$tmp"
else
  mv "$tmp" "$OUT"
fi
echo "gen_nsi: $OUT ($n syscall numbers, matching $SRC)"
